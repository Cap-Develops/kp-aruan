/** Собирает пользовательское сообщение из нескольких распознаваний одного документа. */
export function buildUser(passes: string[]): string {
  const clean = passes.map((p) => (p || '').trim()).filter(Boolean);
  if (clean.length === 1) return clean[0];
  return clean.map((t, i) => `=== ВАРИАНТ ${i + 1} ===\n${t}`).join('\n\n');
}
